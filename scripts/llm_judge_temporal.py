"""Extract structured temporal labels from MAIRA-2 reports using an LLM judge.

Reads the JSON reports generated by eval_maira2_mscxrt.py, sends each to an
LLM (OpenAI GPT-4.1-mini or Anthropic Claude) with a classification prompt,
and extracts {improving, stable, worsening} for the target finding.

Outputs:
  - Per-pair predictions CSV with columns: pair_id, finding, ground_truth, predicted, llm_reasoning
  - Summary metrics JSON (macro_acc, macro_f1, per-finding breakdown)

Usage:
    python scripts/llm_judge_temporal.py --reports data/maira2_reports/standard/all_reports_*.json
    python scripts/llm_judge_temporal.py --reports data/maira2_reports/specific/all_reports_*.json --api anthropic
"""
import argparse
import json
import logging
import os
import sys
import time
from datetime import datetime
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import balanced_accuracy_score, f1_score, confusion_matrix
from tqdm import tqdm

sys.path.insert(0, str(Path(__file__).parent.parent))

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s %(levelname)s %(name)s: %(message)s",
)
logger = logging.getLogger(__name__)

LABEL_MAP = {"improving": 0, "stable": 1, "worsening": 2}
LABEL_NAMES = ["improving", "stable", "worsening"]

SYSTEM_PROMPT = """\
You are an expert radiologist. You will be given a radiology report describing \
chest X-ray findings, and a specific clinical finding to evaluate. Your task is \
to determine whether that finding is IMPROVING, STABLE, or WORSENING based on \
the report's temporal language.

Rules:
- If the report describes the finding as getting better, resolving, decreasing, \
or improved compared to prior, classify as IMPROVING.
- If the report describes the finding as unchanged, similar, stable, or \
persistent without change, classify as STABLE.
- If the report describes the finding as getting worse, increasing, new, \
progressing, or worsened compared to prior, classify as WORSENING.
- If the report does not mention the finding or temporal change at all, use \
your best judgment based on available context. If truly ambiguous, classify \
as STABLE.

Respond with EXACTLY this JSON format (no other text):
{"classification": "improving" | "stable" | "worsening", "reasoning": "one sentence explanation"}
"""

USER_PROMPT_TEMPLATE = """\
Report:
{report}

Finding to evaluate: {finding}

Classify the temporal progression of {finding} as improving, stable, or worsening."""

FINDING_DISPLAY = {
    "consolidation": "consolidation",
    "edema": "pulmonary edema",
    "pleural_effusion": "pleural effusion",
    "pneumonia": "pneumonia",
    "pneumothorax": "pneumothorax",
}


def call_openai(client, model: str, system: str, user: str) -> dict:
    resp = client.chat.completions.create(
        model=model,
        messages=[
            {"role": "system", "content": system},
            {"role": "user", "content": user},
        ],
        temperature=0,
        max_tokens=150,
    )
    text = resp.choices[0].message.content.strip()
    return parse_response(text)


def call_anthropic(client, model: str, system: str, user: str) -> dict:
    resp = client.messages.create(
        model=model,
        system=system,
        messages=[{"role": "user", "content": user}],
        temperature=0,
        max_tokens=150,
    )
    text = resp.content[0].text.strip()
    return parse_response(text)


def parse_response(text: str) -> dict:
    """Parse the LLM JSON response, with fallback for non-JSON output."""
    text = text.strip()
    if text.startswith("```"):
        text = text.split("```")[1]
        if text.startswith("json"):
            text = text[4:]
        text = text.strip()
    try:
        parsed = json.loads(text)
        cls = parsed.get("classification", "").lower().strip()
        reasoning = parsed.get("reasoning", "")
        if cls in LABEL_MAP:
            return {"classification": cls, "reasoning": reasoning, "raw": text}
    except json.JSONDecodeError:
        pass

    # Fallback: look for keywords
    text_lower = text.lower()
    for label in ["improving", "worsening", "stable"]:
        if label in text_lower:
            return {"classification": label, "reasoning": text, "raw": text}
    return {"classification": "stable", "reasoning": f"PARSE_FAILED: {text}", "raw": text}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--reports", required=True,
                        help="Path to consolidated JSON from eval_maira2_mscxrt.py")
    parser.add_argument("--api", choices=["openai", "anthropic"], default="openai")
    parser.add_argument("--model", default=None,
                        help="LLM model name (default: gpt-4.1-mini / claude-sonnet-4-20250514)")
    parser.add_argument("--out_dir", default="results/maira2_judge")
    parser.add_argument("--rate_limit_delay", type=float, default=0.1,
                        help="Seconds between API calls")
    args = parser.parse_args()

    with open(args.reports) as f:
        reports = json.load(f)
    logger.info("Loaded %d reports from %s", len(reports), args.reports)

    if args.api == "openai":
        from openai import OpenAI
        client = OpenAI()
        model = args.model or "gpt-4.1-mini"
        call_fn = lambda sys, usr: call_openai(client, model, sys, usr)
    else:
        import anthropic
        client = anthropic.Anthropic()
        model = args.model or "claude-sonnet-4-20250514"
        call_fn = lambda sys, usr: call_anthropic(client, model, sys, usr)

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    predictions = []
    for rec in tqdm(reports, desc="LLM judge"):
        finding = rec["finding"]
        display = FINDING_DISPLAY.get(finding, finding)
        report_text = rec["maira2_report"]

        user_msg = USER_PROMPT_TEMPLATE.format(report=report_text, finding=display)
        try:
            result = call_fn(SYSTEM_PROMPT, user_msg)
        except Exception as e:
            logger.warning("API error for %s: %s", rec.get("dicom_id"), e)
            result = {"classification": "stable", "reasoning": f"API_ERROR: {e}", "raw": ""}
            time.sleep(2)

        predictions.append({
            "dicom_id": rec["dicom_id"],
            "previous_dicom_id": rec["previous_dicom_id"],
            "finding": finding,
            "ground_truth": rec["ground_truth"],
            "gt_label": rec["label"],
            "predicted": result["classification"],
            "pred_label": LABEL_MAP.get(result["classification"], 1),
            "reasoning": result["reasoning"],
            "maira2_report": report_text,
        })
        time.sleep(args.rate_limit_delay)

    df = pd.DataFrame(predictions)

    # Save predictions
    timestamp = datetime.utcnow().strftime("%Y%m%d_%H%M%S")
    csv_path = out_dir / f"predictions_{timestamp}.csv"
    df.to_csv(csv_path, index=False)
    logger.info("Predictions saved to %s", csv_path)

    # Compute metrics
    from data.dataset import FINDINGS
    all_results = []
    for finding in FINDINGS:
        sub = df[df["finding"] == finding]
        if len(sub) == 0:
            continue
        y_true = sub["gt_label"].values
        y_pred = sub["pred_label"].values
        macro_acc = float(balanced_accuracy_score(y_true, y_pred))
        macro_f1 = float(f1_score(y_true, y_pred, average="macro", zero_division=0))
        cm = confusion_matrix(y_true, y_pred, labels=[0, 1, 2]).tolist()
        all_results.append({
            "finding": finding, "n": len(sub),
            "macro_acc": macro_acc, "macro_f1": macro_f1,
            "confusion_matrix": cm,
        })
        logger.info("  %-20s  n=%d  macro_acc=%.3f  macro_f1=%.3f", finding, len(sub), macro_acc, macro_f1)

    # Average
    accs = [r["macro_acc"] for r in all_results]
    logger.info("  %-20s  macro_acc=%.3f", "AVERAGE", np.mean(accs))

    summary = {
        "model": "maira2",
        "judge_api": args.api,
        "judge_model": model,
        "prompt_mode": Path(args.reports).parent.name,
        "timestamp": timestamp,
        "per_finding": all_results,
        "average_macro_acc": float(np.mean(accs)),
    }
    summary_path = out_dir / f"summary_{timestamp}.json"
    with open(summary_path, "w") as f:
        json.dump(summary, f, indent=2)
    logger.info("Summary saved to %s", summary_path)


if __name__ == "__main__":
    main()
